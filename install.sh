    clear
    echo "Selecione as categorias que deseja instalar:"
    echo "Enter seleciona todos os itens da categoria; → abre o submenu."
    echo
    for index in "${!CATEGORY_NAMES[@]}"; do
      [[ "$index" -eq "$current" ]] && printf ' > ' || printf '   '
      if category_selected "$index"; then
        printf '[x] %s\n' "${CATEGORY_NAMES[index]}"
      elif category_has_selection "$index"; then
        printf '[-] %s\n' "${CATEGORY_NAMES[index]}"
      else
        printf '[ ] %s\n' "${CATEGORY_NAMES[index]}"
      fi
    done
