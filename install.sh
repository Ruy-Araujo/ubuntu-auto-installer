run_categories() {
  local index script name

  for index in "$@"; do
    script="$SCRIPTS_DIR/${CATEGORY_SCRIPTS[index]}"
    name="${CATEGORY_NAMES[index]}"

    if [[ ! -f "$script" ]]; then
      printf 'Script não encontrado: %s\n' "$script" >&2
      continue
    fi

    highlighted_message "Instalando $name..."
    if bash "$script"; then
      highlighted_message "$name instalada com sucesso."
    else
      printf 'Ocorreu um erro durante a instalação de: %s\n' "$name" >&2
    fi
  done
}

post_install() {
  # Mantém o comportamento original apenas para a instalação completa.
  chsh -s "$(command -v zsh)"
  apt update
  apt upgrade -y
  apt autoremove -y
}

install_all() {
  local selected=() index

  for index in "${!CATEGORY_SCRIPTS[@]}"; do
    selected+=("$index")
  done

  run_categories "${selected[@]}"
  post_install
}

run_selected_items() {
  local item
  for item in "${!SELECTED_ITEMS[@]}"; do
    [[ "${SELECTED_ITEMS[$item]}" -eq 1 ]] || continue
    highlighted_message "Instalando ${ITEM_NAMES[$item]}..."
    if bash "$SCRIPTS_DIR/install-item.sh" "$item"; then
      highlighted_message "${ITEM_NAMES[$item]} instalada com sucesso."
    else
      printf 'Ocorreu um erro durante a instalação de: %s\n' "${ITEM_NAMES[$item]}" >&2
    fi
  done
}

category_selected() {
  local item
  for item in ${CATEGORY_ITEMS[$1]}; do
    [[ "${SELECTED_ITEMS[$item]:-0}" -eq 1 ]] || return 1
  done
  return 0
}

toggle_category() {
  local category="$1" item value=1
  category_selected "$category" && value=0
  for item in ${CATEGORY_ITEMS[$category]}; do
    SELECTED_ITEMS[$item]="$value"
  done
}

all_categories_selected() {
  local category
  for category in "${!CATEGORY_NAMES[@]}"; do
    category_selected "$category" || return 1
  done
  return 0
}

category_has_selection() {
  local item
  for item in ${CATEGORY_ITEMS[$1]}; do
    [[ "${SELECTED_ITEMS[$item]:-0}" -eq 1 ]] && return 0
  done
  return 1
}

select_category_items() {
  local category="$1" current=0 key item index
  local -a items=( ${CATEGORY_ITEMS[$category]} )

  while true; do
    clear
    echo "${CATEGORY_NAMES[$category]}"
    echo "Use ↑/↓ para navegar e Enter para marcar/desmarcar."
    echo
    for index in "${!items[@]}"; do
      item="${items[index]}"
      [[ "$index" -eq "$current" ]] && printf ' > ' || printf '   '
      [[ "${SELECTED_ITEMS[$item]:-0}" -eq 1 ]] && printf '[x] %s\n' "${ITEM_NAMES[$item]}" || printf '[ ] %s\n' "${ITEM_NAMES[$item]}"
    done
    echo
    echo "Enter: selecionar | A: todos | Esc: voltar"
    IFS= read -rsn1 key || return 1
    if [[ "$key" == $'\e' ]]; then
      IFS= read -rsn2 -t 0.1 key || true
      case "$key" in
        '[A') current=$(((current - 1 + ${#items[@]}) % ${#items[@]})) ;;
        '[B') current=$(((current + 1) % ${#items[@]})) ;;
        '') return 0 ;;
      esac
      continue
    fi
    case "${key,,}" in
      '') item="${items[current]}"; SELECTED_ITEMS[$item]=$((1 - ${SELECTED_ITEMS[$item]:-0})) ;;
      a) toggle_category "$category" ;;
      q) return 0 ;;
    esac
  done
}

select_categories() {
