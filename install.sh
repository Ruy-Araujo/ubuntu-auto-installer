    echo "Enter: selecionar todos | →: submenu | I: instalar selecionados | A: todos | Esc: voltar"
    IFS= read -rsn1 key || return 1
    # As setas chegam como uma sequência de escape: ESC [ A/B.
    if [[ "$key" == $'\e' ]]; then
      IFS= read -rsn2 -t 0.1 key || true
      case "$key" in
        '[A') current=$(((current - 1 + ${#CATEGORY_NAMES[@]}) % ${#CATEGORY_NAMES[@]})) ;;
        '[B') current=$(((current + 1) % ${#CATEGORY_NAMES[@]})) ;;
        '[C') select_category_items "$current" ;;
        '') return 0 ;;
      esac
      continue
    fi
    case "${key,,}" in
      '' | $'\r') toggle_category "$current" ;;
      a)
        if all_categories_selected; then
          for index in "${!CATEGORY_NAMES[@]}"; do
            category_selected "$index" && toggle_category "$index"
          done
        else
          for index in "${!CATEGORY_NAMES[@]}"; do
            category_selected "$index" || toggle_category "$index"
          done
        fi
        ;;
      i) run_selected_items; return 0 ;;
      q) return 0 ;;
    esac
  done
}

main_menu() {
  local current=0 key
  local -a options=("Instalação completa" "Selecionar itens para instalar")
  while true; do
    clear
    echo "Menu principal"
    echo
    for index in "${!options[@]}"; do
      [[ "$index" -eq "$current" ]] && printf ' > ' || printf '   '
      printf '%s\n' "${options[index]}"
    done
    echo
    echo "Enter: selecionar | Esc: sair"
    IFS= read -rsn1 key || exit 0
    if [[ "$key" == $'\e' ]]; then
      IFS= read -rsn2 -t 0.1 key || exit 0
      case "$key" in
        '[A') current=$(((current - 1 + ${#options[@]}) % ${#options[@]})) ;;
        '[B') current=$(((current + 1) % ${#options[@]})) ;;
        '') exit 0 ;;
      esac
      continue
    fi
    case "${key,,}" in
      '' | $'\r')
        if [[ "$current" -eq 0 ]]; then
          install_all
        else
          select_categories
        fi
        return
        ;;
      q) exit 0 ;;
    esac
  done
}

