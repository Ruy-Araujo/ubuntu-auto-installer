highlighted_message() {
  message="$1"
  length=${#message}

  top_border="╔═$(printf '═%.0s' $(seq 1 $((length + 12))))═╗"
  bottom_border="╚═$(printf '═%.0s' $(seq 1 $((length + 12))))═╝"

  echo "$top_border"
  echo "║ 《✧》 $message 《✧》 ║"
  echo "$bottom_border"
}

